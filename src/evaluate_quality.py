"""
Image Quality Evaluation Tool

Automatically evaluates all compression codecs generated by compress_tif.py using GPU-accelerated metrics:
- PSNR (Peak Signal-to-Noise Ratio): Pixel-level accuracy
- SSIM (Structural Similarity Index): Structural similarity
- LPIPS (Learned Perceptual Image Patch Similarity): Perceptual quality

Usage:
    python src/evaluate_quality.py              # Run with default settings
    python src/evaluate_quality.py --no-plots   # Skip visualization generation

The script automatically:
- Uses the same paths as compress_tif.py (/work/datasets/jump_toy/raw)
- Discovers all .zarr compression codecs in the output directory
- Generates quality comparisons and exports results

Outputs:
1. Terminal table (formatted with rich) showing quality ratings
2. Matplotlib visualizations for first 5 sites
3. CSV exports (detailed per-site and summary statistics)
4. JSON exports (detailed and summary)
"""

